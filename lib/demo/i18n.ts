/** Calendar date (report, evidence and sample dates are dates without a time). */
export function formatDate(iso: string, lang: Lang): string {
  const d = new Date(iso.length === 10 ? iso + "T00:00:00Z" : iso);
  const [day, month, year] = iso.length === 10
    ? [d.getUTCDate(), d.getUTCMonth(), d.getUTCFullYear()]
    : [d.getDate(), d.getMonth(), d.getFullYear()];
  return lang === "ka" ? `${day} ${KA_MONTHS[month]}, ${year}` : `${day} ${EN_MONTHS[month]} ${year}`;
}

/** Date and local time, for events in the demo (answers, approvals). */
export function formatDateTime(iso: string, lang: Lang): string {
  const d = new Date(iso);
  const hm = `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
  return `${formatDate(iso, lang)}, ${hm}`;
}

